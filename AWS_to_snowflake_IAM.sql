DROP TABLE CUSTOMER_RAW_1;

CREATE OR REPLACE TABLE CUSTOMER_RAW_1 (
  CUSTOMER_ID NUMBER,
  CUSTOMER_NAME STRING,
  EMAIL STRING,
  CITY STRING
); 

CREATE OR REPLACE FILE FORMAT CSV_FORMAT
TYPE = CSV 
FIELD_DELIMITER = ','
SKIP_HEADER = 1;

--creating external stage

CREATE OR REPLACE STORAGE INTEGRATION S3_INT
TYPE = EXTERNAL_STAGE
STORAGE_PROVIDER = S3
ENABLED = TRUE
STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::949820256982:role/SNOWFLAKES33CONNECT' 
STORAGE_ALLOWED_LOCATIONS = ('s3://snowflake-iam18/')

DESC INTEGRATION S3_INT;

CREATE OR REPLACE STAGE CUSTOMER_S3_STAGE_IAM
URL = 's3://snowflake-iam18/'
STORAGE_INTEGRATION = S3_INT
FILE_FORMAT = CSV_FORMAT;

LIST @CUSTOMER_S3_STAGE_IAM;

COPY INTO CUSTOMER_RAW_1
FROM @CUSTOMER_S3_STAGE_IAM
FILES = ('customer_raw_1.csv')
FILE_FORMAT = (TYPE = 'CSV' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO CUSTOMER_RAW_1
FROM @CUSTOMER_S3_STAGE_IAM
FILE_FORMAT = (TYPE = 'CSV' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"')
ON_ERROR = 'CONTINUE';

SELECT * FROM CUSTOMER_RAW_1  ORDER BY CUSTOMER_ID LIMIT 10;


