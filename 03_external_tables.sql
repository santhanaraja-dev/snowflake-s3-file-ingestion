CREATE OR REPLACE EXTERNAL TABLE CUSTOMER_EXTERNAL
LOCATION = @CUSTOMER_EXTERNAL
FILE_FORMAT = CSV_FORMAT;


SELECT * FROM CUSTOMER.RAW.CUSTOMER_EXTERNAL;

SELECT *, VALUE:c1::NUMBER AS CUSTOMER_ID,VALUE:c2::VARCHAR AS CUSTOMER_NAME,VALUE:c3::VARCHAR AS EMAIL,
VALUE:c4::VARCHAR AS CITY FROM CUSTOMER_EXTERNAL order by  CUSTOMER_ID;

CREATE OR REPLACE EXTERNAL TABLE CUSTOMER_EXTERNAL_SCHEMA(
  CUSTOMER_ID NUMBER  AS (VALUE:c1::NUMBER),
  CUSTOMER_NAME VARCHAR AS (VALUE:c2::VARCHAR),
  EMAIL  VARCHAR AS (VALUE:c3::VARCHAR),
  CITY  VARCHAR  AS (VALUE:c4::VARCHAR)
)
LOCATION = @CUSTOMER_EXTERNAL
FILE_FORMAT = CSV_FORMAT;

SELECT * FROM CUSTOMER_EXTERNAL_SCHEMA;